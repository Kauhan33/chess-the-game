@pytest.mark.ct("CT-66")
def test_ataque_nenhum_email_ou_caminho_pessoal_em_arquivo():
    allowed = {"noreply@anthropic.com"}
    problems = []
    for path in repository_text_files():
        for number, line in enumerate(path.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            for found in EMAIL.findall(line):
                if found not in allowed and not found.endswith(("users.noreply.github.com", ".png", ".py")):
                    problems.append(f"{path.relative_to(ROOT)}:{number}: {found}")
            if PERSONAL_PATH.search(line):
                problems.append(f"{path.relative_to(ROOT)}:{number}: caminho pessoal")
    assert not problems, problems


