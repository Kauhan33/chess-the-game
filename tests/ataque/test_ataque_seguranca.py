"""Varredura estática: segurança, privacidade e compatibilidade do código e dos arquivos do repositório.

CT-65: jogo sem rede, sem execução dinâmica e sem escrita em disco; só ferramentas e testes gravam, onde pedimos.
CT-66: PNG sem metadados de texto, autoria dos commits só com e-mail noreply e nenhum e-mail ou caminho pessoal em arquivo.
CT-67: todos os módulos valem como Python 3.10, sem biblioteca padrão mais nova, e o que é de Windows fica protegido.

A busca pelos nomes reais não pode ficar aqui, porque escrever os nomes no teste os publicaria. Ela é feita à parte.
"""
from __future__ import annotations

import ast
import re
import shutil
import struct
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
GAME_FILES = sorted((ROOT / "xadrez").rglob("*.py"))
TOOL_FILES = sorted((ROOT / "tools").rglob("*.py")) + [ROOT / "main.py"]
TEST_FILES = sorted(path for path in (ROOT / "tests").rglob("*.py") if "ataque" not in path.parts)
ALL_PY = GAME_FILES + TOOL_FILES + TEST_FILES

FORBIDDEN_IMPORTS = {
    "socket", "ssl", "http", "urllib", "ftplib", "smtplib", "telnetlib", "xmlrpc", "requests", "asyncio",
    "subprocess", "multiprocessing", "pickle", "marshal", "shelve", "dbm", "sqlite3", "tempfile", "webbrowser",
}
# Geram a documentação: chamam Java, navegador, pytest e gh de propósito, e nada disso vai no jogo.
DOCUMENT_TOOLS = {"gerar_documentacao.py", "gerar_pdf.py", "gerar_uml.py", "preparar_github.py", "relatorio_testes.py"}
FORBIDDEN_CALLS = {"eval", "exec", "compile", "__import__", "open"}
WRITE_METHODS = {"write_text", "write_bytes", "mkdir", "unlink", "rmdir", "rename", "touch"}
NEWER_STDLIB = {"tomllib", "wsgiref.types", "asyncio.taskgroups"}
NEWER_NAMES = {
    ("enum", "StrEnum"), ("enum", "ReprEnum"), ("typing", "Self"), ("typing", "LiteralString"), ("typing", "Never"),
    ("typing", "NotRequired"), ("typing", "Required"), ("typing", "Unpack"), ("typing", "assert_never"),
    ("typing", "reveal_type"), ("typing", "override"), ("itertools", "batched"), ("datetime", "UTC"),
}
TEXT_SUFFIXES = {".py", ".md", ".toml", ".txt", ".yml", ".yaml", ".json", ".cfg", ".ini", ".gitignore", ".gitattributes"}
# Com -nometadata, o único texto que o PlantUML ainda grava no PNG é este crédito, sem dado da máquina.
PLANTUML_CREDIT = b"copyleft\x00Generated by https://plantuml.com"
EMAIL = re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+")
PERSONAL_PATH = re.compile(r"(?:[A-Za-z]:[\\/](?:Users|Claude)|/home/\w|/Users/\w)")


def parsed(path: Path) -> ast.AST:
    return ast.parse(path.read_text(encoding="utf-8"), filename=str(path))


def imported_modules(tree: ast.AST) -> set[str]:
    modules = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            modules.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
            modules.add(node.module)
    return modules


def repository_text_files() -> list[Path]:
    """Só o que o git publicaria. Sem git, os arquivos de texto do projeto, menos os testes deste ataque."""
    git = shutil.which("git")
    if git is not None and (ROOT / ".git").exists():
        listing = subprocess.run([git, "ls-files"], cwd=ROOT, capture_output=True, text=True, encoding="utf-8", check=True)
        paths = [ROOT / line for line in listing.stdout.splitlines()]
    else:
        paths = [path for path in ROOT.rglob("*") if path.is_file() and ".git" not in path.parts]
    return [path for path in paths if path.suffix in TEXT_SUFFIXES or path.name in TEXT_SUFFIXES]


@pytest.mark.ct("CT-65")
@pytest.mark.parametrize("path", GAME_FILES + TOOL_FILES, ids=lambda path: path.relative_to(ROOT).as_posix())
def test_ataque_sem_rede_nem_execucao_dinamica(path):
    tree = parsed(path)
    roots = {name.split(".")[0] for name in imported_modules(tree)}
    forbidden = FORBIDDEN_IMPORTS - {"subprocess"} if path.name in DOCUMENT_TOOLS else FORBIDDEN_IMPORTS
    assert not roots & forbidden, f"importa {roots & forbidden}"
    called = {node.func.id for node in ast.walk(tree) if isinstance(node, ast.Call) and isinstance(node.func, ast.Name)}
    assert not called & FORBIDDEN_CALLS, f"chama {called & FORBIDDEN_CALLS}"


