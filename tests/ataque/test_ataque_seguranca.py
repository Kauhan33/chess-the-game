@pytest.mark.ct("CT-66")
@pytest.mark.parametrize("path", sorted(ROOT.glob("docs/**/*.png")), ids=lambda path: path.name)
def test_ataque_png_sem_metadados(path):
    data = path.read_bytes()
    assert data[:8] == b"\x89PNG\r\n\x1a\n"
    position, extras = 8, []
    while position < len(data):
        length, kind = struct.unpack(">I4s", data[position:position + 8])
        payload = data[position + 8:position + 8 + length]
        is_plantuml_credit = kind == b"tEXt" and payload == PLANTUML_CREDIT
        if kind not in (b"IHDR", b"IDAT", b"IEND", b"PLTE", b"tRNS", b"sRGB", b"gAMA", b"pHYs") and not is_plantuml_credit:
            extras.append(kind)
        position += 12 + length
    assert not extras, f"pedaços com possível texto: {extras}"


