@pytest.mark.ct("CT-67")
@pytest.mark.parametrize("path", ALL_PY, ids=lambda path: path.relative_to(ROOT).as_posix())
def test_ataque_sem_biblioteca_padrao_mais_nova_que_3_10(path):
    tree = parsed(path)
    assert not imported_modules(tree) & NEWER_STDLIB
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module:
            for alias in node.names:
                assert (node.module, alias.name) not in NEWER_NAMES, f"{node.module}.{alias.name} não existe no 3.10"
        if isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name):
            assert (node.value.id, node.attr) not in NEWER_NAMES, f"{node.value.id}.{node.attr} não existe no 3.10"
        assert type(node).__name__ not in ("TryStar", "TypeAlias", "TypeVarTuple", "ParamSpec"), type(node).__name__


